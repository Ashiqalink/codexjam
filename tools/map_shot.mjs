import path from 'node:path';
import puppeteer from 'puppeteer-core';
import { createServer } from 'vite';
const server = await createServer({ root: path.resolve('.'), logLevel: 'error', server: { port: 5198, strictPort: true, hmr: false, watch: null, host: '127.0.0.1' } });
await server.listen();
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: 'new', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'], defaultViewport: { width: 1280, height: 900 } });
const page = await browser.newPage();
page.on('console', (m) => console.log('[c]', m.text().slice(0, 200)));
page.on('pageerror', (e) => console.log('[err]', e.message));
await page.goto('http://127.0.0.1:5198/index.html?skip&unlock');
await page.waitForFunction(() => window.__G && window.__G.time > 0.5, { timeout: 60000 });
await page.keyboard.press('KeyM');
await new Promise((r) => setTimeout(r, 1500));
await page.mouse.move(640, 450);
await new Promise((r) => setTimeout(r, 500));
const cv = await page.$('#map canvas');
await cv.screenshot({ path: 'shots/map_check.png' });
await page.screenshot({ path: 'shots/map_full.png' });
await browser.close(); await server.close();
